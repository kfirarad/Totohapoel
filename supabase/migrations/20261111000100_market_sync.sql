-- Log of market-sync runs (the Edge Function in supabase/functions/market-sync).
-- Super-admins see it in the app; the function writes with the service role.
create table public.sync_runs (
  id bigint generated by default as identity primary key,
  market text not null,
  kind text not null check (kind in ('import', 'results')),
  status text not null default 'running' check (status in ('running', 'ok', 'skipped', 'error')),
  message text,
  stats jsonb,                 -- e.g. {"columns_created": 1, "results_updated": 7}
  started_at timestamptz not null default now(),
  finished_at timestamptz
);
create index sync_runs_recent_idx on public.sync_runs (market, kind, started_at desc);

alter table public.sync_runs enable row level security;
revoke all on public.sync_runs from anon;
create policy sync_runs_select on public.sync_runs for select to authenticated using (public.is_super_admin());
